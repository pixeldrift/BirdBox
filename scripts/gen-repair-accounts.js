// Builds sql/batches/repair-accounts.sql: everything sql/038 does, as plain one-statement-at-a-time SQL (no functions, no DO blocks),
// safe to run on a database where 038 only half-ran, or ran completely. Ends with a status table — every row should say true.
//   node scripts/gen-repair-accounts.js
const fs = require('fs');
const path = require('path');

const TABLES = [['birds', 'id'], ['contacts', 'id'], ['transactions', 'id'], ['health_records', 'id'], ['buildings', 'code'], ['waybills', 'id'],
  ['media', 'id'], ['media_links', 'media_id, target_type, target_id'], ['bird_transfers', 'id'], ['locations', 'id'], ['cages', 'code'], ['rooms', 'id'],
  ['aviary', 'id'], ['users', 'id'], ['supplies', 'id'], ['care_items', 'id'], ['tasks', 'id'], ['task_done', 'id'], ['events', 'id'], ['event_links', 'id'],
  ['navigation', 'id'], ['test_rules', 'id'], ['show_results', 'id']];
const ACCOUNT = "nullif(current_setting('app.account_id', true), '')";

let o = `-- REPAIR / FINISH sql 038 (user accounts) — plain statements, safe to run any number of times.
-- Run it in the Neon SQL editor. The last result is a status table: every line should say true.
-- Generated by scripts/gen-repair-accounts.js.

create table if not exists accounts (id text primary key, name text not null default 'My Aviary', created_at timestamptz not null default now());
create table if not exists auth_links (auth_id text primary key, account_id text not null, user_id text, email text not null default '', created_at timestamptz not null default now());
grant birdbox_app to current_user;
grant usage on schema public to birdbox_app;
grant select on species, species_names to birdbox_app;
grant usage on all sequences in schema public to birdbox_app;
`;
for (const [t, pk] of TABLES) {
  o += `
-- ${t}
alter table ${t} add column if not exists account_id text;
alter table ${t} add column if not exists is_demo boolean not null default false;
update ${t} set account_id = 'legacy' where account_id is null;
alter table ${t} alter column account_id set default ${ACCOUNT};
alter table ${t} alter column account_id set not null;
alter table ${t} drop constraint if exists ${t}_pkey cascade;
alter table ${t} add primary key (account_id, ${pk});
alter table ${t} enable row level security;
alter table ${t} force row level security;
drop policy if exists tenant_isolation on ${t};
create policy tenant_isolation on ${t} using (account_id = ${ACCOUNT}) with check (account_id = ${ACCOUNT});
drop policy if exists demo_read on ${t};
create policy demo_read on ${t} for select using (account_id = 'demo' and current_setting('app.loading_demo', true) = 'on');
grant select, insert, update, delete on ${t} to birdbox_app;
`;
}
o += `
-- links between tables include the account
alter table media_links drop constraint if exists media_links_media_fk;
alter table media_links add constraint media_links_media_fk foreign key (account_id, media_id) references media (account_id, id) on delete cascade;

-- rules that were "one per database" are now "one per account"
drop index if exists birds_band_unique;
create unique index if not exists birds_band_unique on birds (account_id, upper(regexp_replace(band, '[[:space:]]+', '', 'g'))) where band is not null;
alter table task_done drop constraint if exists task_done_task_id_on_date_sub_key_key;
alter table task_done drop constraint if exists task_done_unique;
alter table task_done add constraint task_done_unique unique (account_id, task_id, on_date, sub_key);
alter table event_links drop constraint if exists event_links_event_id_target_type_target_id_key;
alter table event_links drop constraint if exists event_links_unique;
alter table event_links add constraint event_links_unique unique (account_id, event_id, target_type, target_id);
alter table test_rules drop constraint if exists test_rules_disease_key;
alter table test_rules drop constraint if exists test_rules_unique;
alter table test_rules add constraint test_rules_unique unique (account_id, disease);

-- accounts and auth_links: you can only see your own
insert into accounts (id, name) select 'legacy', 'My Aviary' where not exists (select 1 from accounts where id = 'legacy');
insert into accounts (id, name) select 'demo', 'Demo Aviary' where not exists (select 1 from accounts where id = 'demo');
alter table accounts enable row level security;
alter table accounts force row level security;
drop policy if exists tenant_isolation on accounts;
create policy tenant_isolation on accounts using (id = ${ACCOUNT}) with check (id = ${ACCOUNT});
grant select, insert, update, delete on accounts to birdbox_app;
alter table auth_links enable row level security;
alter table auth_links force row level security;
drop policy if exists own_login on auth_links;
create policy own_login on auth_links using (auth_id = nullif(current_setting('app.auth_id', true), '')) with check (auth_id = nullif(current_setting('app.auth_id', true), ''));
grant select, insert, update, delete on auth_links to birdbox_app;

-- STATUS: every line below should say true
select what, ok from (
  select 1 as n, 'accounts and auth_links tables exist' as what, to_regclass('public.accounts') is not null and to_regclass('public.auth_links') is not null as ok
  union all select 2, 'app role can read auth_links', has_table_privilege('birdbox_app', 'auth_links', 'select')
  union all select 3, 'app role can write accounts', has_table_privilege('birdbox_app', 'accounts', 'insert')
${TABLES.map(([t], i) => `  union all select ${4 + i}, '${t}: has account_id, security on, app role has access', exists (select 1 from information_schema.columns where table_name = '${t}' and column_name = 'account_id') and (select relforcerowsecurity from pg_class where relname = '${t}') and has_table_privilege('birdbox_app', '${t}', 'select, insert, update, delete')`).join('\n')}
) s order by n;
`;
fs.writeFileSync(path.join(__dirname, '..', 'sql', 'batches', 'repair-accounts.sql'), o);
console.log('wrote sql/batches/repair-accounts.sql', o.split('\n').length, 'lines');

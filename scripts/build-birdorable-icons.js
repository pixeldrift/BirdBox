// Links each Birdorable illustration to its species by eBird code, writing
// js/data/icon-species-birdorable.js (code -> image path) for the Birdorable icon pack.
//
//   node scripts/build-birdorable-icons.js [--file taxonomy.json]   (otherwise downloads the taxonomy)
//
// Birdorable names are matched against eBird's common names, our US display names and alternate
// names (same normalisation as the species search). Names that match nothing, or several species,
// are listed so they can be fixed in MANUAL below — they are never guessed.

const fs = require('fs');
const path = require('path');
const { buildAliases, displayName } = require('./seed-species');

const ROOT = path.join(__dirname, '..');
const MAP = path.join(ROOT, 'src/images/Birdorable/species-map.json');
const OUT = path.join(ROOT, 'js/data/icon-species-birdorable.js');

// Birdorable name -> eBird scientific name, for names the matcher can't reach.
const MANUAL = {
  // Birdorable calls these Amazons "Parrot"; eBird/US aviculture say Amazon.
  'Yellow-naped Parrot': 'Amazona auropalliata', 'Red-lored Parrot': 'Amazona autumnalis',
  'White-fronted Parrot': 'Amazona albifrons', 'Orange-winged Parrot': 'Amazona amazonica',
  'Vinaceous Parrot': 'Amazona vinacea', 'Blue-fronted Parrot': 'Amazona aestiva',
  'Mealy Parrot': 'Amazona farinosa', 'Saint Lucia Parrot': 'Amazona versicolor',
  "Lord Derby's Parakeet": 'Psittacula derbiana', 'Golden-collared Macaw': 'Primolius auricollis',
  // Names eBird files under a newer or more specific name.
  'Atlantic Canary': 'Serinus canaria', 'Harris Hawk': 'Parabuteo unicinctus',
  'Common Pheasant': 'Phasianus colchicus', 'Brant Goose': 'Branta bernicla',
  'Common Kestrel': 'Falco tinnunculus', 'Common Moorhen': 'Gallinula chloropus',
  'Red-headed Parrotfinch': 'Erythrura psittacea', 'Hoopoe': 'Upupa epops',
  'Jackdaw': 'Coloeus monedula', 'Secretary Bird': 'Sagittarius serpentarius',
  'Cattle Egret': 'Ardea ibis', 'Sage Grouse': 'Centrocercus urophasianus',
  'Lammergeier': 'Gypaetus barbatus', 'Sacred Ibis': 'Threskiornis aethiopicus', 'Blackbird': 'Turdus merula',
};

function normalize(s) {
  return String(s).toLowerCase().replace(/-/g, ' ').replace(/['’]/g, '').replace(/\./g, '')
    .replace(/&/g, ' and ').replace(/grey/g, 'gray').replace(/\s+/g, ' ').trim();
}

async function main() {
  const fileArg = process.argv.indexOf('--file');
  const taxonomy = fileArg !== -1
    ? JSON.parse(fs.readFileSync(process.argv[fileArg + 1], 'utf8'))
    : await (await fetch('https://api.ebird.org/v2/ref/taxonomy/ebird?fmt=json&cat=species')).json();

  const index = new Map();
  const add = (name, code) => {
    const n = normalize(name);
    if (!index.has(n)) index.set(n, new Set());
    index.get(n).add(code);
  };
  taxonomy.forEach((r) => {
    add(r.comName, r.speciesCode);
    const d = displayName(r);
    if (d) add(d, r.speciesCode);
  });
  buildAliases(taxonomy).rows.forEach((r) => add(r[1], r[0]));
  const bySci = new Map(taxonomy.map((r) => [r.sciName, r.speciesCode]));

  const species = JSON.parse(fs.readFileSync(MAP, 'utf8')).species;
  const icons = {};
  const unmatched = [], ambiguous = [], clashes = [];
  Object.keys(species).forEach((hash) => {
    const e = species[hash];
    let code = MANUAL[e.species] ? bySci.get(MANUAL[e.species]) : null;
    if (!code) {
      const hits = index.get(normalize(e.species));
      if (!hits) { unmatched.push(e.species); return; }
      if (hits.size > 1) {
        // Several species share the name (Clements splits "Eclectus Parrot" into four): one
        // illustration serves each of them.
        ambiguous.push(e.species + ' (' + Array.from(hits).join(', ') + ')');
        hits.forEach((c) => { if (!icons[c]) icons[c] = 'src/images/Birdorable/' + e.files[0]; });
        return;
      }
      code = Array.from(hits)[0];
    }
    if (icons[code]) clashes.push(e.species + ' vs ' + icons[code]);
    else icons[code] = 'src/images/Birdorable/' + e.files[0];
  });

  const lines = Object.keys(icons).sort().map((c) => '  ' + JSON.stringify(c) + ': ' + JSON.stringify(icons[c]) + ',');
  fs.writeFileSync(OUT, '// Generated by scripts/build-birdorable-icons.js — do not edit by hand.\n' +
    '// Birdorable illustration per species, keyed by eBird species code.\n' +
    'var BIRDORABLE_SPECIES_ICONS = {\n' + lines.join('\n') + '\n};\n');
  console.log('Linked ' + Object.keys(icons).length + ' of ' + Object.keys(species).length + ' Birdorable species.');
  console.log('Unmatched (' + unmatched.length + '): ' + unmatched.join(', '));
  console.log('Shared by several species (' + ambiguous.length + '): ' + ambiguous.join(', '));
  console.log('Two images for one species (' + clashes.length + '): ' + clashes.join(' | '));
}

main().catch((err) => { console.error(err.message); process.exit(1); });
